"""Детектор мата/оскорблений по корням слов (можно дополнять)."""

# Корни в нижнем регистре. "ё" приводится к "е" перед проверкой.
_ROOTS = [
    "бля", "бляд", "хуй", "хуя", "хуё", "хуе", "хуи", "хую", "хуел",
    "пизд", "пиzd", "пидор", "пидр", "пидарас",
    "гандон", "мудак", "мудaк", "мудил",
    "ебал", "ебат", "ебучий", "ебу", "еби", "ебут", "ёб", "ёба", "ёбан",
    "заеб", "наеб", "оху", "аху", "поху", "нахуй",
    "сука", "сукин", "сукa", "шлюх", "шлюш", "проститутк",
    "говно", "гавно", "дерьмо", "срать", "ссать", "ссыт", "сру",
    "уеб", "уёб", "долбо", "чмо", "мразь", "тварь", "гнид", "козл",
    "залуп", "манда",
    "даун", "дебил", "идиот", "кретин", "тупиц",
    "хер", "хрен", "нахер", "нафиг",
    "сучк", "псих", "лох", "лошар",
]

_COMPILED = tuple(r.lower() for r in _ROOTS)

# Частые разговорные фразы, которые участники не считают матом, —
# их не наказываем, даже если внутри есть корень мата.
_ALLOWED_PHRASES = (
    "иди на хуй", "иди нахуй", "иди на хуя",
    "иди на хер", "иди нахер", "иди нафиг", "иди на фиг",
)


def contains_profanity(text: str) -> bool:
    low = text.lower().replace("ё", "е")
    for phrase in _ALLOWED_PHRASES:
        if phrase in low:
            return False
    for root in _COMPILED:
        if root in low:
            return True
    return False
